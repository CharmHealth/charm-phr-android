    /**
     * This a callback object for the [ImageReader]. "onImageAvailable" will be called when a
     * still image is ready to be saved.
     */
    private val onImageAvailableListener = ImageReader.OnImageAvailableListener {

        val file = File(FileUtil.getFolderPathAsSting(requireActivity(), ModelUtil.folderTemp), FileUtil.getImageFileNameStamp())

        file.createNewFile()

        Log.d(TAG, "file.path ${file.path}")

        Log.d(TAG, "onImageAvailableListener ${mdCameraViewModel.capturedImageFileArr}")

        backgroundHandler?.post {

            val image = it?.acquireNextImage()
            val allowCompression = true

            val buffer = image?.planes?.firstOrNull()?.buffer
            if (buffer != null) {
                val bytes = ByteArray(buffer.remaining())
                buffer.get(bytes)
                var output: FileOutputStream? = null
                try {
                    output = FileOutputStream(file).apply {
                        write(bytes)
                    }
                } catch (e: IOException) {
                    Log.d(TAG, e.toString())
                } finally {
                    image.close()
                    output?.let {
                        try {
                            it.close()
                        } catch (e: IOException) {
                            Log.d(TAG, e.toString())
                        }
                    }

                }

            }

            if (allowCompression) {

                Log.d(TAG, "MdCameraImageSaver befrore compression :${file.length() / 1000000F}Mb")

                val tempFile = FileUtil.createNewFile(FileUtil.FileType.TEMP, FileUtil.FileExtension.IMG, requireActivity())

                try {

                    val mdCompressor = MdCompressor(
                        context = requireActivity(),
                        maxWidth = 1080, maxHeight = 1280,
                        quality = 95,
                        compressFormat = Bitmap.CompressFormat.JPEG,
                        destinationFilePath = tempFile.absolutePath
                    )

                    Log.d(TAG, "MdCameraImageSaver outPutFile after compression :${file.length() / 1000000F}Mb")

                    val filepath = mdCompressor.compressToFile(file)
                    if (filepath != null)
                        mdCameraViewModel.capturedImageFileArr.add(file.path)
                    else {
                        requireActivity().runOnUiThread { UIUtil.showToast(requireActivity(), R.string.something_went_wrong, Toast.LENGTH_SHORT) }
                    }

                    tempFile.copyTo(file, overwrite = true)

                    tempFile.delete()

                } catch (e: IOException) {
                    Log.d(TAG, e.toString())
                }

            }

            requireActivity().runOnUiThread {
                binding.cameraCaptureButton?.isEnabled = true
            }

        }

        requireActivity().runOnUiThread {
            binding.cameraCaptureButton?.isEnabled = false
        }

        if (mdCameraViewModel.cameraCaptureType == CameraCaptureType.SINGLE_SHOT) {

            intentCallBack?.intentToImageCropperFragment(file.path)

        } else /*if (mdCameraViewModel.cameraCaptureType == CameraCaptureType.MULTI_SHOT)*/ {

            if (mdCameraViewModel.multiShotFirstTime) //for the first time
                intentCallBack?.intentToPreviewFragment()
            else {
                requireActivity().runOnUiThread {
                    Log.d(TAG, "onImageAvailableListener addItemAndScrollToLastlyAdded")
                    mdCaptureCameraThumbnailAdapter.addItemAndScrollToLastlyAdded(file.path)
                }
            }
        }


    }

    /**
     * A [CameraCaptureSession.CaptureCallback] that handles events related to JPEG capture.
     */
    private val captureCallback = object : CameraCaptureSession.CaptureCallback() {

        private fun process(result: CaptureResult) {

            when (state) {

                STATE_PREVIEW -> {

                } // Do nothing when the camera preview is working normally.

                STATE_WAITING_LOCK -> {

                    Log.d(TAG, "process state STATE_WAITING_LOCK")
                    capturePicture(result)
                }

                STATE_WAITING_PRECAPTURE -> {

                    Log.d(TAG, "process state STATE_WAITING_PRECAPTURE")

                    // CONTROL_AE_STATE can be null on some devices
                    val aeState = result.get(CaptureResult.CONTROL_AE_STATE)
                    if (aeState == null || aeState == CaptureResult.CONTROL_AE_STATE_PRECAPTURE ||
                        aeState == CaptureRequest.CONTROL_AE_STATE_FLASH_REQUIRED
                    ) {

                        state = STATE_WAITING_NON_PRECAPTURE
                    }

                }

                STATE_WAITING_NON_PRECAPTURE -> {

                    Log.d(TAG, "process state STATE_WAITING_NON_PRECAPTURE")

                    // CONTROL_AE_STATE can be null on some devices
                    val aeState = result.get(CaptureResult.CONTROL_AE_STATE)
                    if (aeState == null || aeState != CaptureResult.CONTROL_AE_STATE_PRECAPTURE) {
                        state = STATE_PICTURE_TAKEN
                        captureStillPicture()
                    }

                }

            }
        }

        private fun capturePicture(result: CaptureResult) {

            val afState = result.get(CaptureResult.CONTROL_AF_STATE)

            if (afState == null) {

                state = STATE_PICTURE_TAKEN
                captureStillPicture()

            } else if (afState == CaptureResult.CONTROL_AF_STATE_FOCUSED_LOCKED
                || afState == CaptureResult.CONTROL_AF_STATE_NOT_FOCUSED_LOCKED
                || afState == CaptureResult.CONTROL_AF_STATE_PASSIVE_FOCUSED
            ) {

                // CONTROL_AE_STATE can be null on some devices
                val aeState = result.get(CaptureResult.CONTROL_AE_STATE)

                if (aeState == null || aeState == CaptureResult.CONTROL_AE_STATE_CONVERGED) {

                    state = STATE_PICTURE_TAKEN
                    captureStillPicture()

                } else runPreCaptureSequence()

            } else if (!isFocusAllowed) { //not all camera are focusable
                state = STATE_PICTURE_TAKEN
                captureStillPicture()
            }

        }

        override fun onCaptureProgressed(
            session: CameraCaptureSession,
            request: CaptureRequest,
            partialResult: CaptureResult
        ) {
            process(partialResult)
        }

        override fun onCaptureCompleted(
            session: CameraCaptureSession,
            request: CaptureRequest,
            result: TotalCaptureResult
        ) {
            process(result)
        }

    }

