    private fun setFlash(requestBuilder: CaptureRequest.Builder) {

        when (cameraFlashState) {

            FlashState.AUTO_FLASH -> {
                if (flashSupported) {
                    Log.d(TAG, "AUTO_FLASH")
                    requestBuilder.set(
                        CaptureRequest.CONTROL_AE_MODE,
                        CaptureRequest.CONTROL_AE_MODE_ON_AUTO_FLASH
                    )
                    requestBuilder.set(
                        CaptureRequest.FLASH_MODE,
                        CaptureRequest.FLASH_MODE_OFF
                    )
                }
            }

            FlashState.FLASH_ON -> {

                if (flashSupported) {
                    Log.d(TAG, "FLASH_ON")
                    requestBuilder.set(
                        CaptureRequest.CONTROL_AE_MODE,
                        CaptureRequest.CONTROL_AE_MODE_ON_ALWAYS_FLASH
                    )
                    requestBuilder.set(
                        CaptureRequest.FLASH_MODE,
                        CaptureRequest.FLASH_MODE_OFF
                    )
                }
            }

            FlashState.FLASH_OFF -> {
                Log.d(TAG, "FLASH_OFF")
                requestBuilder.set(
                    CaptureRequest.CONTROL_AE_MODE,
                    CaptureRequest.CONTROL_AE_MODE_ON
                )
                requestBuilder.set(
                    CaptureRequest.FLASH_MODE,
                    CaptureRequest.FLASH_MODE_OFF
                )

            }

        }


    }

    private fun resetFlashMode() {

        try {

            //first stop the existing repeating request
            captureSession?.stopRepeating()

            //cancel any existing AF trigger (repeated touches, etc.)
            previewRequestBuilder.set(CaptureRequest.CONTROL_AF_TRIGGER, CameraMetadata.CONTROL_AF_TRIGGER_CANCEL)
            previewRequestBuilder.set(CaptureRequest.CONTROL_AF_MODE, CaptureRequest.CONTROL_AF_MODE_OFF)
            captureSession?.capture(previewRequestBuilder.build(), captureCallback, backgroundHandler)

            previewRequestBuilder.set(CaptureRequest.CONTROL_MODE, CameraMetadata.CONTROL_MODE_AUTO)
            previewRequestBuilder.set(CaptureRequest.CONTROL_AF_MODE, CaptureRequest.CONTROL_AF_MODE_AUTO)
            previewRequestBuilder.set(CaptureRequest.CONTROL_AF_TRIGGER, CameraMetadata.CONTROL_AF_TRIGGER_START)

            setFlash(previewRequestBuilder)

            captureSession?.setRepeatingRequest(previewRequest, captureCallback, backgroundHandler)

        } catch (e: CameraAccessException) {
            Log.d(TAG, "unlockFocus :CameraAccessException:$e")
            intentCallBack?.setFinalResult()
        } catch (e: IllegalStateException) {
            Log.d(TAG, "unlockFocus :CameraAccessException:$e")
            intentCallBack?.setFinalResult()
        }

    }

    /**
     * Opens the camera specified by [cameraId].
     */
    private fun openCamera(width: Int, height: Int) {

        val permission = PermissionUtil.checkPermission(requireActivity(), arrayOf(Manifest.permission.CAMERA))
        if (!permission) checkPermissionAndOpenCamera(width, height)

        setUpCameraOutputs(width, height)
        configureTransform(width, height)

        if (previewSize == null) {
            intentCallBack?.setFinalResult()
            return
        }

        val manager = requireActivity().getSystemService(Context.CAMERA_SERVICE) as CameraManager
        try {
            // Wait for camera to open - 2.5 seconds is sufficient
            if (!cameraOpenCloseLock.tryAcquire(2500, TimeUnit.MILLISECONDS)) {
                intentCallBack?.setFinalResult()
            }
            manager.openCamera(cameraId, stateCallback, backgroundHandler)
        } catch (e: CameraAccessException) {
            Log.d(TAG, e.toString())
        } catch (e: InterruptedException) {
            Log.d(TAG, e.toString())
        }

    }

    /**
     * Sets up member variables related to camera.
     *
     * @param width  The width of available size for camera preview
     * @param height The height of available size for camera preview
     */
    private fun setUpCameraOutputs(width: Int, height: Int) {

        val manager = requireActivity().getSystemService(Context.CAMERA_SERVICE) as CameraManager

        try {

            for (cameraId in manager.cameraIdList) { //Looping util the required camera arrives

                val characteristics = manager.getCameraCharacteristics(cameraId)

                // We don't use a front facing camera in this sample.
                val cameraDirection = characteristics.get(CameraCharacteristics.LENS_FACING)
                if (cameraDirection != null) {

                    if (isOnlyFrontCameraAllowed) {

                        if (cameraDirection != CameraCharacteristics.LENS_FACING_FRONT) {
                            continue
                        } //Until front camera arrives - skip

                    } else {

                        if (cameraDirection == CameraCharacteristics.LENS_FACING_FRONT) {
                            continue
                        } //Until other than front camera arrives - skip
                    }

                }

                val map = characteristics.get(
                    CameraCharacteristics.SCALER_STREAM_CONFIGURATION_MAP
                ) ?: continue

                // For still image captures, we use the largest available size.
                val largest = Collections.max(
                    Arrays.asList(*map.getOutputSizes(ImageFormat.JPEG)),
                    CompareSizesByArea()
                )
                imageReader = ImageReader.newInstance(
                    largest.width, largest.height,
                    ImageFormat.JPEG, 2
                ).apply {
                    setOnImageAvailableListener(onImageAvailableListener, backgroundHandler)
                }

                // Find out if we need to swap dimension to get the preview size relative to sensor
                // coordinate.


                val displaySize = Point()
                val displayRotation = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
                    val windowMetrics =
                        requireActivity().windowManager.currentWindowMetrics
                    val insets: Insets = windowMetrics.windowInsets
                        .getInsetsIgnoringVisibility(WindowInsets.Type.systemBars())
                    displaySize.x = windowMetrics.bounds.width() - insets.left - insets.right
                    displaySize.y = windowMetrics.bounds.height() - insets.top - insets.bottom
                    requireActivity().display?.rotation ?: 0
                } else {
                    requireActivity().windowManager.defaultDisplay.getSize(displaySize)
                    requireActivity().windowManager.defaultDisplay.rotation
                }
                sensorOrientation = characteristics.get(CameraCharacteristics.SENSOR_ORIENTATION) ?: 0
                val swappedDimensions = areDimensionsSwapped(displayRotation)


                val rotatedPreviewWidth = if (swappedDimensions) height else width
                val rotatedPreviewHeight = if (swappedDimensions) width else height

                Log.d(TAG, "rotatedPreviewWidth $rotatedPreviewWidth rotatedPreviewHeight $rotatedPreviewHeight")

                var maxPreviewWidth = if (swappedDimensions) displaySize.y else displaySize.x
                var maxPreviewHeight = if (swappedDimensions) displaySize.x else displaySize.y

                if (maxPreviewWidth > MAX_PREVIEW_WIDTH) maxPreviewWidth = MAX_PREVIEW_WIDTH
                if (maxPreviewHeight > MAX_PREVIEW_HEIGHT) maxPreviewHeight = MAX_PREVIEW_HEIGHT

                // Danger, W.R.! Attempting to use too large a preview size could  exceed the camera
                // bus' bandwidth limitation, resulting in gorgeous previews but the storage of
                // garbage capture data.
                previewSize = chooseOptimalSize(
                    map.getOutputSizes(SurfaceTexture::class.java),
                    rotatedPreviewWidth, rotatedPreviewHeight,
                    maxPreviewWidth, maxPreviewHeight,
                    largest
                )

                val previewSize = previewSize

                if (previewSize == null) return
                else {

                    // We fit the aspect ratio of TextureView to the size of preview we picked.
                    if (resources.configuration.orientation == Configuration.ORIENTATION_LANDSCAPE) {
                        Log.d(TAG, "ORIENTATION_LANDSCAPE")
                        binding.cameraFragmentTextureView.setAspectRatio(previewSize.width, previewSize.height)
                    } else {
                        Log.d(TAG, "ORIENTATION_PORTRAIT")
                        binding.cameraFragmentTextureView.setAspectRatio(previewSize.height, previewSize.width)
                    }

                    // Check if the flash is supported.

                    if (characteristics.get(CameraCharacteristics.FLASH_INFO_AVAILABLE) == true) {
                        flashSupported = true
                        binding.cameraFlashBtn.visibility = View.VISIBLE
                    } else {
                        flashSupported = false
                        binding.cameraFlashBtn.visibility = View.GONE
                    }

                    this.cameraId = cameraId

                    setFocusFeatureForActiveCamera(manager)

                    // We've found a viable camera and finished setting up member variables,
                    // so we don't need to iterate through other available cameras.

                    return

                }


            }

        } catch (e: CameraAccessException) {
            Log.d(TAG, "setUpCameraOutputs e:$e")
            intentCallBack?.setFinalResult()
        } catch (e: NullPointerException) {
            // Currently an NPE is thrown when the Camera2API is used but not supported on the
            // device this code runs.
            Log.d(TAG, "setUpCameraOutputs e:$e")
            intentCallBack?.setFinalResult()
        }

    }

    /**
     * Determines if the dimensions are swapped given the phone's current rotation.
     *
     * @param displayRotation The current rotation of the display
     *
     * @return true if the dimensions are swapped, false otherwise.
     * */
    private fun areDimensionsSwapped(displayRotation: Int): Boolean {

        Log.d(TAG, "displayRotation: $displayRotation")
        var swappedDimensions = false

        when (displayRotation) {

            Surface.ROTATION_0, Surface.ROTATION_180 -> {
                if (sensorOrientation == 90 || sensorOrientation == 270) {
                    swappedDimensions = true
                }
            }

            Surface.ROTATION_90, Surface.ROTATION_270 -> {
                if (sensorOrientation == 0 || sensorOrientation == 180) {
                    swappedDimensions = true
                }
            }

            else -> Log.d(TAG, "Display rotation is invalid: $displayRotation")

        }

        Log.d(TAG, "swappedDimensions $swappedDimensions")

        return swappedDimensions
    }

    /**
     * Starts a background thread and its [Handler].
     */
    private fun startBackgroundThread() {

        backgroundThread = HandlerThread("CameraBackground").also { it.start() }
        backgroundHandler = Handler(backgroundThread?.looper ?: Looper.getMainLooper())
    }

    /**
     * Creates a new [CameraCaptureSession] for camera preview.
     */
    private fun createCameraPreviewSession() {

        try {

            val texture = binding.cameraFragmentTextureView.surfaceTexture

            val previewSize = previewSize ?: return

            // We configure the size of default buffer to be the size of camera preview we want.
            texture?.setDefaultBufferSize(previewSize.width, previewSize.height)

            // This is the output Surface we need to start preview.
            val surface = Surface(texture)

            // We set up a CaptureRequest.Builder with the output Surface.
            previewRequestBuilder = cameraDevice!!.createCaptureRequest(
                CameraDevice.TEMPLATE_PREVIEW
            )
            previewRequestBuilder.addTarget(surface)

            // Here, we create a CameraCaptureSession for camera preview.

            try {
                cameraDevice?.createCaptureSession(
                    Arrays.asList(surface, imageReader?.surface),
                    object : CameraCaptureSession.StateCallback() {

                        override fun onConfigured(cameraCaptureSession: CameraCaptureSession) {
                            // The camera is already closed
                            if (cameraDevice == null) return

                            // When the session is ready, we start displaying the preview.
                            captureSession = cameraCaptureSession
                            try {

                                // Auto focus should be continuous for camera preview.
                                previewRequestBuilder.set(
                                    CaptureRequest.CONTROL_AF_MODE,
                                    CaptureRequest.CONTROL_AF_MODE_CONTINUOUS_PICTURE
                                )

                                // Flash is automatically enabled when necessary.
                                setFlash(previewRequestBuilder)

                                // Finally, we start displaying the camera preview.
                                previewRequest = previewRequestBuilder.build()
                                captureSession?.setRepeatingRequest(previewRequest, captureCallback, backgroundHandler)

                            } catch (e: CameraAccessException) {
                                Log.d(TAG, "createCameraPreviewSession onConfigured : CameraAccessException e:$e")
                                cameraDevice?.close()
                                intentCallBack?.setFinalResult()
                            } catch (e: IllegalStateException) {
                                Log.d(TAG, "createCameraPreviewSession onConfigured : IllegalStateException e:$e")
                                cameraDevice?.close()
                                intentCallBack?.setFinalResult()
                            }

                        }

                        override fun onConfigureFailed(session: CameraCaptureSession) {
                            Log.d(TAG, "createCameraPreviewSession onConfigureFailed")
                            cameraDevice?.close()
                            intentCallBack?.setFinalResult()
                        }
                    }, null
                )

            } catch (e: IllegalStateException) {
                Log.d(TAG, "createCameraPreviewSession : IllegalStateException e:$e")
                cameraDevice?.close()
                intentCallBack?.setFinalResult()
            }

        } catch (e: CameraAccessException) {

            Log.d(TAG, "createCameraPreviewSession : IllegalStateException e:$e")
            cameraDevice?.close()
            intentCallBack?.setFinalResult()

        }

    }

    /**
     * Configures the necessary [android.graphics.Matrix] transformation to `cameraFragmentTextureView`.
     * This method should be called after the camera preview size is determined in
     * setUpCameraOutputs and also the size of `cameraFragmentTextureView` is fixed.
     *
     * @param viewWidth  The width of `cameraFragmentTextureView`
     * @param viewHeight The height of `cameraFragmentTextureView`
     */
    private fun configureTransform(viewWidth: Int, viewHeight: Int) {

        activity ?: return

        val previewSize = previewSize ?: return

        val rotation = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            requireActivity().display?.rotation ?: 0
        } else {
            requireActivity().windowManager.defaultDisplay.rotation
        }
        val matrix = Matrix()
        val viewRect = RectF(0f, 0f, viewWidth.toFloat(), viewHeight.toFloat())
        val bufferRect = RectF(0f, 0f, previewSize.height.toFloat(), previewSize.width.toFloat())
        val centerX = viewRect.centerX()
        val centerY = viewRect.centerY()

        if (Surface.ROTATION_90 == rotation || Surface.ROTATION_270 == rotation) {
            bufferRect.offset(centerX - bufferRect.centerX(), centerY - bufferRect.centerY())
            val scale = Math.max(
                viewHeight.toFloat() / previewSize.height,
                viewWidth.toFloat() / previewSize.width
            )
            with(matrix) {
                setRectToRect(viewRect, bufferRect, Matrix.ScaleToFit.FILL)
                postScale(scale, scale, centerX, centerY)
                postRotate((90 * (rotation - 2)).toFloat(), centerX, centerY)
            }
        } else if (Surface.ROTATION_180 == rotation) {
            matrix.postRotate(180f, centerX, centerY)
        }
        binding.cameraFragmentTextureView.setTransform(matrix)
    }

