    /**
     * Capture a still picture. This method should be called when we get a response in
     * [.captureCallback] from both [.lockFocus].
     */
    private fun captureStillPicture() {

        Log.d(TAG, "captureStillPicture")

        try {

            val imgReaderSurface = imageReader?.surface
            if (activity == null || cameraDevice == null || imgReaderSurface == null) return
            val rotation = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
                requireActivity().display?.rotation ?: 0
            } else {
                requireActivity().windowManager.defaultDisplay.rotation
            }
            // This is the CaptureRequest.Builder that we use to take a picture.
            val captureBuilder = cameraDevice?.createCaptureRequest(
                CameraDevice.TEMPLATE_STILL_CAPTURE
            )?.apply {

                addTarget(imgReaderSurface)

                Log.d(TAG, " rotation: ${ORIENTATIONS.get(rotation)}")
                Log.d(TAG, "sensorOrientation $sensorOrientation")

                // Sensor orientation is 90 for most devices, or 270 for some devices (eg. Nexus 5X)
                // We have to take that into account and rotate JPEG properly.
                // For devices with orientation of 90, we return our mapping from ORIENTATIONS.
                // For devices with orientation of 270, we need to rotate the JPEG 180 degrees.

                val finalRotation = (ORIENTATIONS.get(rotation) + sensorOrientation + 270) % 360
                set(CaptureRequest.JPEG_ORIENTATION, finalRotation)
                Log.d(TAG, "finalRotation $finalRotation")

                // Use the same AE and AF modes as the preview.
                set(
                    CaptureRequest.CONTROL_AF_MODE,
                    CaptureRequest.CONTROL_AF_MODE_AUTO
                )
            }?.also { setFlash(it) }

            val captureCallback = object : CameraCaptureSession.CaptureCallback() {

                override fun onCaptureCompleted(
                    session: CameraCaptureSession,
                    request: CaptureRequest,
                    result: TotalCaptureResult
                ) {
                    unlockFocus()
                }
            }

            captureSession?.apply {

                stopRepeating()
                abortCaptures()

                val cb = captureBuilder?.build()
                if (cb != null) {
                    capture(cb, captureCallback, null)
                }

            }
        } catch (e: CameraAccessException) {
            Log.d(TAG, "captureStillPicture CameraAccessException : e:$e")
            intentCallBack?.setFinalResult()
        }

    }

