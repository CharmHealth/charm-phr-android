    //region After capture

    /**
     * Unlock the focus. This method should be called when still image capture sequence is
     * finished.
     */
    private fun unlockFocus() {

        Log.d(TAG, "unlockFocus")

        try {

            // Reset the auto-focus trigger
            previewRequestBuilder.set(
                CaptureRequest.CONTROL_AF_TRIGGER,
                CameraMetadata.CONTROL_AF_TRIGGER_CANCEL
            )

            setFlash(previewRequestBuilder)

            captureSession?.capture(
                previewRequestBuilder.build(), captureCallback,
                backgroundHandler
            )
            // After this, the camera will go back to the normal state of preview.
            state = STATE_PREVIEW
            captureSession?.setRepeatingRequest(
                previewRequest, captureCallback,
                backgroundHandler
            )

            requireActivity().runOnUiThread {
                binding.cameraCaptureButton?.isEnabled = true
            }


        } catch (e: CameraAccessException) {
            Log.d(TAG, "unlockFocus :CameraAccessException:$e")
            intentCallBack?.setFinalResult()
        } catch (e: IllegalStateException) {
            Log.d(TAG, "unlockFocus :CameraAccessException:$e")
            intentCallBack?.setFinalResult()
        }

    }

    /**
     * Closes the current [CameraDevice].
     */
    private fun closeCamera() {

        try {
            cameraOpenCloseLock.acquire()
            captureSession?.close()
            captureSession = null
            cameraDevice?.close()
            cameraDevice = null
            imageReader?.close()
            imageReader = null

        } catch (e: InterruptedException) {
            Log.d(TAG, "closeCamera : InterruptedException:$e")
            intentCallBack?.setFinalResult()
        } finally {
            cameraOpenCloseLock.release()
        }
    }

    /**
     * Stops the background thread and its [Handler].
     */
    private fun stopBackgroundThread() {

        backgroundThread?.quitSafely()
        try {
            backgroundThread?.join()
            backgroundThread = null
            backgroundHandler = null
        } catch (e: InterruptedException) {
            Log.d(TAG, e.toString())
            intentCallBack?.setFinalResult()
        }
    }

